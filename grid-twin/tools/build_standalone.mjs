// Builds one self-contained HTML file of Grid Twin that opens with a double-click: no web server, no install.
// CSS, every source module and every network data set are inlined; only Three.js and the fonts still come
// from public CDNs, so it needs an internet connection.
//
//   node grid-twin/tools/build_standalone.mjs        # writes grid_twin.html at the top of the repo
//
// Re-run it after changing anything in grid-twin/ so the single-file copy stays current.
// No dependencies: each module is wrapped in its own function scope and its imports become plain lookups.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "..", "grid_twin.html");
const read = (p) => readFileSync(join(root, p), "utf8");

// Dependency order: a module comes after everything it imports.
const ORDER = ["bb84", "detector", "network", "teleport", "response", "scene", "ui", "main"];
const external = new Set(); // imports of three and its addons, resolved by the page's import map
const parts = [];
for (const name of ORDER) {
  let code = read(`src/${name}.js`);
  const exports = [];
  code = code.replace(/^import\s+(.+?)\s+from\s+"(.+?)";\s*$/gm, (line, what, from) => {
    if (!from.startsWith("./")) {
      external.add(line.trim());
      return "";
    }
    const dep = from.slice(2, -3);
    if (!ORDER.slice(0, ORDER.indexOf(name)).includes(dep)) throw new Error(`${name} imports ${dep}, which is not built before it`);
    return `const ${what.replace(/\s+as\s+/g, ": ")} = __${dep};`;
  });
  code = code.replace(/^export\s+(function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, id) => {
    exports.push(id);
    return `${kind} ${id}`;
  });
  if (/^export\s/m.test(code)) throw new Error(`${name}: unsupported export form`);
  parts.push(`// ---- src/${name}.js\nconst __${name} = (() => {\n${code}\nreturn { ${exports.join(", ")} };\n})();`);
}
const bundle = `${[...external].join("\n")}\n\n${parts.join("\n\n")}\n`;

// Every data file the page can ask for, keyed by the same relative path it fetches.
const data = { "data/network.json": JSON.parse(read("data/network.json")) };
for (const f of readdirSync(join(root, "data/networks"))) if (f.endsWith(".json")) data[`data/networks/${f}`] = JSON.parse(read(`data/networks/${f}`));
const safe = (s) => s.replace(/<\/(script)/gi, "<\\/$1"); // never close the inline script early
const dataJs = JSON.stringify(data).replace(/</g, "\\u003c");

let html = read("index.html");
const css = read("style.css");
const swap = (a, b) => {
  if (!html.includes(a)) throw new Error(`index.html changed: cannot find ${a}`);
  html = html.replace(a, () => b);
};
swap('<link rel="stylesheet" href="style.css" />', `<style>\n${css}\n</style>`);
swap(
  '<script type="module" src="src/main.js"></script>',
  `<script>window.GRIDTWIN_DATA = ${dataJs};</script>\n  <script type="module">\n${safe(bundle)}</script>`,
);
html = html.replace("<head>", "<head>\n  <!-- Generated by grid-twin/tools/build_standalone.mjs from grid-twin/. Edit the sources there, then rebuild. -->");
writeFileSync(out, html);
console.log(`wrote ${out} (${(html.length / 1024).toFixed(0)} KB, ${ORDER.length} modules, ${Object.keys(data).length} data files)`);
